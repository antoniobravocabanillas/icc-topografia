import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { PrismaClient } from "@prisma/client";
import { workspaceInvitationHandlers } from "../lib/server/workspace-invitation-http";
import { createWorkspaceInvitation as create, acceptWorkspaceInvitation as accept, manageWorkspaceInvitation as manage, WorkspaceInvitationError } from "../lib/terraqo/workspace-invitations";

async function main() {
  const url = new URL(process.env.DATABASE_URL || "");
  assert.equal(url.hostname, "127.0.0.1");
  assert.equal(url.username, "terraqo_s22_test");
  assert.equal(process.env.TERRAQO_LOCAL_S22_TEST, "synthetic-only");
  const db = new PrismaClient();
  const rejects = (promise: Promise<unknown>, status: number) => assert.rejects(promise, (e: unknown) => e instanceof WorkspaceInvitationError && e.status === status);
  try {
    const owner = await db.user.create({ data: { email: "owner@invite.invalid", emailVerified: new Date() } });
    const recipient = await db.user.create({ data: { email: "recipient@invite.invalid" } });
    const ws = await db.terraqoWorkspace.create({ data: { name: "Invitations synthetic", slug: "invitation-test" } });
    const other = await db.terraqoWorkspace.create({ data: { name: "Other invitations", slug: "invitation-other" } });
    await db.terraqoWorkspaceMember.createMany({ data: [ws, other].map(w => ({ workspaceId: w.id, userId: owner.id, role: "OWNER" as const })) });
    const input = { workspaceId: ws.id, email: recipient.email!, operationKey: randomUUID() };
    let actorId: string | null = owner.id;
    let enabled = true;
    const http = workspaceInvitationHandlers({ db, actor: async () => actorId, enabled: () => enabled, deliver: async () => "disabled" });
    const endpoint = "https://workspace.invalid/api/terraqo/workspace-invitations";
    const post = (body: unknown, origin = "https://workspace.invalid", contentType = "application/json") => http.POST(new Request(endpoint, { method: "POST", headers: { origin, "content-type": contentType }, body: JSON.stringify(body) }));
    const command = { action: "create", ...input, email: "http@invite.invalid", operationKey: randomUUID() };
    enabled = false;
    assert.equal((await post(command)).status, 404);
    enabled = true;
    actorId = null;
    assert.equal((await post(command)).status, 401);
    actorId = owner.id;
    assert.equal((await post(command, "https://foreign.invalid")).status, 403);
    assert.equal((await post(command, "")).status, 403);
    assert.equal((await post(command, "https://workspace.invalid", "text/plain")).status, 415);
    assert.equal((await post({ ...command, actorId: owner.id })).status, 422);
    assert.equal((await post({ ...command, role: "ADMIN" })).status, 422);
    assert.equal((await post({ ...command, email: "x".repeat(5000) })).status, 413);
    const oversized = new Request(endpoint, { method: "POST", headers: { origin: "https://workspace.invalid", "content-type": "application/json", "content-length": "1" }, body: JSON.stringify({ padding: "x".repeat(5000) }) });
    assert.equal((await http.POST(oversized)).status, 413);
    assert.equal(await db.terraqoWorkspaceInvitation.count(), 0);
    const createdResponse = await post(command);
    assert.equal(createdResponse.status, 201);
    assert.equal(createdResponse.headers.get("cache-control"), "private, no-store");
    const httpInvite = await createdResponse.json();
    assert.equal((await (await post(command)).json()).token, null);
    const listing = await http.GET(new Request(`${endpoint}?workspaceId=${ws.id}`));
    assert.equal(listing.status, 200);
    const publicRow = (await listing.json()).invitations[0];
    for (const secret of ["token", "tokenHash", "operationKey", "operationFingerprint"]) assert.equal(secret in publicRow, false);
    actorId = recipient.id;
    assert.equal((await http.GET(new Request(`${endpoint}?workspaceId=${ws.id}`))).status, 403);
    assert.equal((await post({ action: "accept", token: httpInvite.token })).status, 404);
    actorId = owner.id;
    assert.equal((await post({ action: "cancel", workspaceId: other.id, invitationId: httpInvite.id })).status, 404);
    assert.equal((await post({ action: "cancel", workspaceId: ws.id, invitationId: httpInvite.id })).status, 200);
    console.log("PASS S22 Request/Response boundary: feature flag, session identity, origin, bounded bytes, schema, no writes on rejection, creation, replay, private projection and tenant isolation. Session dependency injected; browser login remains pending.");
    await rejects(create(db, recipient.id, input), 403);
    await assert.rejects(create(db, owner.id, { ...input, role: "ADMIN" }));
    const invite = await create(db, owner.id, input);
    assert.ok(invite.token);
    assert.equal((await create(db, owner.id, input)).token, null);
    await rejects(create(db, owner.id, { ...input, email: "different@invite.invalid" }), 409);
    const stored = await db.terraqoWorkspaceInvitation.findUniqueOrThrow({ where: { id: invite.id } });
    assert.equal(stored.role, "VIEWER");
    assert.notEqual(stored.tokenHash, invite.token);
    assert.equal(await db.terraqoWorkspaceMember.count({ where: { userId: recipient.id } }), 0);
    await rejects(accept(db, owner.id, invite.token), 404);
    await rejects(accept(db, recipient.id, invite.token), 404);
    await db.user.update({ where: { id: recipient.id }, data: { emailVerified: new Date() } });
    const accepted = await Promise.all([accept(db, recipient.id, invite.token), accept(db, recipient.id, invite.token)]);
    assert.equal(accepted.filter(r => !r.replayed).length, 1);
    assert.equal(await db.terraqoWorkspaceMember.count({ where: { userId: recipient.id, workspaceId: ws.id } }), 1);
    const fresh = () => create(db, owner.id, { ...input, operationKey: randomUUID() });
    const cancel = await fresh();
    await rejects(manage(db, owner.id, other.id, cancel.id, "cancel"), 404);
    await manage(db, owner.id, ws.id, cancel.id, "cancel");
    await manage(db, owner.id, ws.id, cancel.id, "cancel");
    await rejects(accept(db, recipient.id, cancel.token!), 404);
    const rotated = await fresh();
    await rejects(manage(db, owner.id, ws.id, rotated.id, "rotate"), 429);
    await db.terraqoWorkspaceInvitation.update({ where: { id: rotated.id }, data: { lastIssuedAt: new Date(Date.now() - 61000) } });
    const next = await manage(db, owner.id, ws.id, rotated.id, "rotate");
    assert.ok(next.token);
    await rejects(accept(db, recipient.id, rotated.token!), 404);
    await db.terraqoWorkspaceMember.update({ where: { workspaceId_userId: { workspaceId: ws.id, userId: recipient.id } }, data: { role: "ADMIN" } });
    await accept(db, recipient.id, next.token);
    assert.equal((await db.terraqoWorkspaceMember.findUniqueOrThrow({ where: { workspaceId_userId: { workspaceId: ws.id, userId: recipient.id } } })).role, "ADMIN");
    const suspended = await fresh();
    await db.terraqoWorkspaceMember.update({ where: { workspaceId_userId: { workspaceId: ws.id, userId: recipient.id } }, data: { active: false } });
    await rejects(accept(db, recipient.id, suspended.token!), 409);
    await db.terraqoWorkspaceInvitation.update({ where: { id: suspended.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
    await rejects(accept(db, recipient.id, suspended.token!), 404);
    const races = await Promise.allSettled([fresh(), fresh()]);
    assert.equal(races.filter(r => r.status === "fulfilled").length, 1);
    assert.equal(races.filter(r => r.status === "rejected").length, 1);
    const pending = await db.terraqoWorkspaceInvitation.findFirstOrThrow({ where: { workspaceId: ws.id, status: "PENDING", expiresAt: { gt: new Date() } } });
    await db.terraqoWorkspaceInvitation.update({ where: { id: pending.id }, data: { resendCount: 5, lastIssuedAt: new Date(Date.now() - 61000) } });
    await rejects(manage(db, owner.id, ws.id, pending.id, "rotate"), 429);
    await manage(db, owner.id, ws.id, pending.id, "cancel");
    const revokedIssuer = await fresh();
    await db.terraqoWorkspaceMember.update({ where: { workspaceId_userId: { workspaceId: ws.id, userId: owner.id } }, data: { role: "VIEWER" } });
    await rejects(accept(db, recipient.id, revokedIssuer.token!), 403);
    console.log("PASS S22 invitations: authorization, minimal role, hashed token, idempotency, verified recipient, concurrent acceptance, tenant isolation, cancellation, rotation, role preservation, suspension, expiry and duplicate creation.");
  } finally { await db.$disconnect(); }
}
main().catch(error => { console.error(error instanceof Error ? error.message : "Invitation test failed"); process.exitCode = 1; });
