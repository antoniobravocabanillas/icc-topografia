import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {createHash} from 'node:crypto';
import {rootCertificates} from 'node:tls';
import {Client} from 'pg';
import path from 'node:path';
assert.ok(process.argv.includes('--confirm=read-only-backup'));
const siteId='2d38524a-44f9-4473-8a1f-9270e03bc2bf';
const base='c623ec8e70d27c04babc3cb0ac6c594b00bc4cfc';
const require=createRequire(new URL('../node_modules/netlify-cli/package.json',import.meta.url));
const {getAPIToken}=await import(pathToFileURL(require.resolve('@netlify/dev-utils')).href);
const {NetlifyAPI}=await import(pathToFileURL(require.resolve('@netlify/api')).href);
const run=promisify(execFile);
let db,stage='site';
try {
 const api=new NetlifyAPI(await getAPIToken());
 const site=await api.getSite({site_id:siteId});
 assert.equal(site.ssl_url,'https://terraqoglobal.com');
 assert.equal(site.published_deploy.commit_ref,base,'Production changed: review candidate base first');
 const entries=await api.getEnvVars({accountId:site.account_slug,siteId});
 const entry=entries.find(e=>e.key==='DATABASE_URL')?.values.find(v=>v.context==='production')?.value;
 assert.ok(entry);
 const url=new URL(entry);assert.equal(url.hostname,'db.prisma.io');assert.equal(url.searchParams.get('schema'),'icc');
 url.searchParams.set('sslmode','verify-full');
 stage='database';
 db=new Client({connectionString:url.toString(),connectionTimeoutMillis:15000,statement_timeout:30000});
 await db.connect();
 await db.query('BEGIN READ ONLY');
 const ledger=(await db.query('SELECT migration_name,checksum,finished_at IS NOT NULL AS finished,rolled_back_at IS NOT NULL AS rolled_back FROM icc._prisma_migrations ORDER BY migration_name')).rows;
 assert.ok(!ledger.some(r=>!r.finished&&!r.rolled_back),'Unfinished migration');
 assert.ok(!ledger.some(r=>r.migration_name==='20261104000200_customer_attention_followup'&&!r.rolled_back),'Followup already applied: inspect before continuing');
 const columns=(await db.query("SELECT column_name FROM information_schema.columns WHERE table_schema='icc' AND table_name='ChatConversation' ORDER BY ordinal_position")).rows.map(r=>r.column_name);
 assert.ok(!columns.includes('nextAction'),'Unexpected followup columns');
 await db.query('COMMIT');
 await db.end();db=null;
 const directory=path.join('C:/Users/Binv/.terraqo-private',`attention-${new Date().toISOString().replace(/[:.]/g,'-')}`);
 await mkdir(directory,{recursive:true});
 const roots=path.join(directory,'root-certificates.pem');await writeFile(roots,rootCertificates.join('\n'));
 const env=Object.fromEntries(Object.entries(process.env).filter(([key])=>['PATH','SYSTEMROOT','WINDIR','TEMP','TMP','USERPROFILE','APPDATA','LOCALAPPDATA'].includes(key.toUpperCase())));
 Object.assign(env,{PGHOST:url.hostname,PGPORT:url.port||'5432',PGDATABASE:decodeURIComponent(url.pathname.slice(1)),PGUSER:decodeURIComponent(url.username),PGPASSWORD:decodeURIComponent(url.password),PGSSLMODE:'verify-full',PGSSLROOTCERT:roots,PGCONNECT_TIMEOUT:'15'});
 const dump=path.join(directory,'icc.dump');stage='backup';
 await run('C:/Program Files/PostgreSQL/18/bin/pg_dump.exe',['--format=custom','--schema=icc','--no-owner','--no-privileges','--file',dump],{env,windowsHide:true,shell:false,timeout:180000,maxBuffer:1024*1024});
 const bytes=await readFile(dump);assert.ok(bytes.length>1000);
 const manifest={at:new Date().toISOString(),siteId,sourceCommit:base,sourceDeploy:site.published_deploy.id,sha256:createHash('sha256').update(bytes).digest('hex'),bytes:bytes.length,ledger,columns,readOnly:true};
 await writeFile(path.join(directory,'manifest.json'),JSON.stringify(manifest,null,2));
 await mkdir('output',{recursive:true});await writeFile('output/attention-production-backup.json',JSON.stringify({directory,...manifest},null,2));
 console.log(JSON.stringify({backup:directory,sha256:manifest.sha256,bytes:manifest.bytes,readOnly:true,restoreStillRequired:true}));
} catch { console.error(`Attention production backup failed at ${stage}; no migration or deploy was attempted.`);process.exitCode=1; }
finally { if(db) await db.end().catch(()=>{}); }
