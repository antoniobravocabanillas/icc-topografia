import { verifyAttentionRouting } from "./test-attention-routing-postgres";
import { verifyChatHttp } from "./test-customer-chat-http";
import { customerChatHistory } from "../lib/server/customer-chat-history";
import { attentionMetrics } from "../lib/server/customer-attention-metrics";
import { postCustomerBot } from "../lib/server/customer-chatbot";
import { issueCustomerChatAccess, verifyCustomerChatAccess } from "../lib/server/customer-chat-access";
import { loadPublicAttentionContext, publicAttentionPresentation, attentionOriginAllowed } from "../lib/server/public-attention-context";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { PrismaClient } from "@prisma/client";
import { mutateCustomerChat, ChatOperationError } from "../lib/server/customer-chat-operations";
import { postCustomerChat, PublicChatError } from "../lib/server/public-customer-chat";
import { saveAttentionSettings } from "../lib/server/customer-attention-settings";
import { attentionConfigSchema, defaultAttentionConfig, attentionAvailability, attentionAccentText } from "../lib/terraqo/customer-attention-config";
import { customerChatSelect } from "../lib/server/customer-chat-projection";
async function main() {
 const url = new URL(process.env.DATABASE_URL || "");
 assert.equal(url.hostname, "127.0.0.1"); assert.equal(url.username, "terraqo_attention_test");
 assert.equal(process.env.TERRAQO_LOCAL_ATTENTION_TEST, "synthetic-only");
 const db = new PrismaClient();
 try {
  const a = await db.user.create({ data: { email: "agent-a@chat.invalid" } });
  const b = await db.user.create({ data: { email: "agent-b@chat.invalid" } });
  const w = await db.terraqoWorkspace.create({ data: { name: "Chat synthetic", slug: "chat-synthetic" } });
  const other = await db.terraqoWorkspace.create({ data: { name: "Chat other", slug: "chat-other" } });
  const chat = await db.chatConversation.create({ data: { terraqoWorkspaceId: w.id, customerName: "Synthetic visitor" } });
  const actor = { workspaceId: w.id, userId: a.id, canManage: true };
  await assert.rejects(mutateCustomerChat(db, { ...actor, workspaceId: other.id }, chat.id, { kind: "take" }), ChatOperationError);
  const claims = await Promise.allSettled([mutateCustomerChat(db, actor, chat.id, { kind: "take" }), mutateCustomerChat(db, { ...actor, userId: b.id }, chat.id, { kind: "take" })]);
  assert.equal(claims.filter(r => r.status === "fulfilled").length, 1);
  const claimed = await db.chatConversation.findUniqueOrThrow({ where: { id: chat.id } });
  const winner = { ...actor, userId: claimed.assignedToId!, canManage: false };
  const loser = { ...winner, userId: winner.userId === a.id ? b.id : a.id };
  const reply = { kind: "reply" as const, body: "Synthetic response", operationKey: randomUUID() };
  await assert.rejects(mutateCustomerChat(db, loser, chat.id, reply), ChatOperationError);
  await Promise.all([mutateCustomerChat(db, winner, chat.id, reply), mutateCustomerChat(db, winner, chat.id, reply)]);
  assert.equal(await db.chatMessage.count({ where: { conversationId: chat.id } }), 1);
  await assert.rejects(mutateCustomerChat(db, winner, chat.id, { ...reply, body: "Different content" }), ChatOperationError);
  const adminReply = { ...reply, operationKey: randomUUID() };
  await mutateCustomerChat(db, { ...loser, canManage: true }, chat.id, adminReply);
  assert.equal((await db.chatConversation.findUniqueOrThrow({ where: { id: chat.id } })).assignedToId, winner.userId);
  const foreignProfile = await db.staffProfile.create({ data: { terraqoWorkspaceId: other.id, displayName: "Other agent", roleTitle: "Support", tools: {} } });
  await assert.rejects(mutateCustomerChat(db, actor, chat.id, { kind: "assign", profileId: foreignProfile.id, expectedAssignment: JSON.stringify([claimed.assignedToId, claimed.assignedProfileId]) }), ChatOperationError);
  const transferChat = await db.chatConversation.create({ data: { terraqoWorkspaceId: w.id, customerName: "Transfer fixture" } });
  const localProfile = await db.staffProfile.create({ data: { terraqoWorkspaceId: w.id, userId: b.id, displayName: "Local agent", roleTitle: "Support", tools: {} } });
  const transfer = { kind: "assign" as const, profileId: localProfile.id, expectedAssignment: JSON.stringify([null, null]) };
  await mutateCustomerChat(db, actor, transferChat.id, transfer);
  await assert.rejects(mutateCustomerChat(db, actor, transferChat.id, transfer), ChatOperationError);
  const transferred = await db.chatConversation.findUniqueOrThrow({ where: { id: transferChat.id } });
  assert.equal(transferred.assignedToId, b.id);
  assert.equal(transferred.assignedProfileId, localProfile.id);
  await db.chatConversation.delete({ where: { id: transferChat.id } });
  const note = { kind: "note" as const, body: "Internal only", operationKey: randomUUID() };
  await assert.rejects(mutateCustomerChat(db, loser, chat.id, note), ChatOperationError);
  await Promise.all([mutateCustomerChat(db, winner, chat.id, note), mutateCustomerChat(db, winner, chat.id, note)]);
  assert.equal(await db.activityLog.count({ where: { entityId: chat.id, title: "Nota interna" } }), 1);
  const dueAt = new Date(Date.now() + 3600000);
  await assert.rejects(mutateCustomerChat(db, loser, chat.id, { kind: "followup", title: "Call", dueAt }), ChatOperationError);
  await mutateCustomerChat(db, winner, chat.id, { kind: "followup", title: "Confirmar alcance", dueAt });
  await assert.rejects(mutateCustomerChat(db, winner, chat.id, { kind: "completeFollowup", expectedAt: new Date(0) }), ChatOperationError);
  await mutateCustomerChat(db, winner, chat.id, { kind: "completeFollowup", expectedAt: dueAt });
  await mutateCustomerChat(db, winner, chat.id, { kind: "completeFollowup", expectedAt: dueAt });
  await mutateCustomerChat(db, winner, chat.id, { kind: "close" });
  await assert.rejects(mutateCustomerChat(db, winner, chat.id, { ...reply, operationKey: randomUUID() }), ChatOperationError);
  await mutateCustomerChat(db, winner, chat.id, reply); // Retry receipt does not reopen resolved chat.
  assert.equal((await db.chatConversation.findUniqueOrThrow({ where: { id: chat.id } })).status, "CLOSED");
  assert.equal(await db.activityLog.count({ where: { entityId: chat.id } }), 7);
  const publicDto = await db.chatConversation.findUniqueOrThrow({ where: { id: chat.id }, select: customerChatSelect });
  assert.deepEqual(Object.keys(publicDto.assignedTo!).sort(), ["image", "name"]);
  assert.equal("customerEmail" in publicDto, false);
  assert.ok(!JSON.stringify(publicDto).includes("Internal only"));
  const creation = { name: "Visitor", email: "visitor@example.invalid", body: "A question", operationKey: randomUUID() };
  const beginnings = await Promise.all([postCustomerChat(db, w.id, creation), postCustomerChat(db, w.id, creation)]);
  assert.equal(beginnings[0].conversationId, beginnings[1].conversationId);
  const visitorId = beginnings[0].conversationId;
  assert.equal(await db.notification.count({ where: { terraqoWorkspaceId: w.id } }), 1);
  await assert.rejects(postCustomerChat(db, w.id, { ...creation, body: "Different" }), PublicChatError);
  const customerMessage = { conversationId: visitorId, body: "More information", operationKey: randomUUID() };
  await Promise.all([postCustomerChat(db, w.id, customerMessage), postCustomerChat(db, w.id, customerMessage)]);
  assert.equal(await db.chatMessage.count({ where: { conversationId: visitorId } }), 2);
  assert.equal(await db.notification.count({ where: { terraqoWorkspaceId: w.id } }), 2);
  await assert.rejects(postCustomerChat(db, other.id, customerMessage), PublicChatError);
  await assert.rejects(postCustomerChat(db, w.id, { ...customerMessage, body: "x".repeat(8001) }));
  const company = await db.company.create({ data: { terraqoWorkspaceId: w.id, legalName: "Synthetic company" } });
  const commercial = { ...actor, canCommercial: true };
  const conversion = { kind: "createOpportunity" as const, title: "Survey service", companyId: company.id, operationKey: randomUUID() };
  await assert.rejects(mutateCustomerChat(db, actor, visitorId, conversion), ChatOperationError);
  await Promise.all([mutateCustomerChat(db, commercial, visitorId, conversion), mutateCustomerChat(db, commercial, visitorId, conversion)]);
  assert.equal(await db.opportunity.count({ where: { terraqoWorkspaceId: w.id } }), 1);
  const opportunity = await db.opportunity.findFirstOrThrow({ where: { terraqoWorkspaceId: w.id } });
  await mutateCustomerChat(db, commercial, visitorId, { kind: "linkOpportunity", opportunityId: opportunity.id });
  assert.equal(await db.activityLog.count({ where: { entityId: visitorId, opportunityId: opportunity.id } }), 1);
  await assert.rejects(mutateCustomerChat(db, { ...commercial, workspaceId: other.id }, visitorId, { kind: "linkOpportunity", opportunityId: opportunity.id }), ChatOperationError);
  await mutateCustomerChat(db, commercial, chat.id, { kind: "linkOpportunity", opportunityId: opportunity.id });
  await db.sale.createMany({ data: [
    { number: "SYNTH-PEN", terraqoWorkspaceId: w.id, opportunityId: opportunity.id, currency: "PEN", amount: "150.25", status: "CONFIRMED" },
    { number: "SYNTH-USD", terraqoWorkspaceId: w.id, opportunityId: opportunity.id, currency: "USD", amount: "20.10", status: "PENDING" },
    { number: "SYNTH-FOREIGN", terraqoWorkspaceId: other.id, opportunityId: opportunity.id, currency: "PEN", amount: "9999.99", status: "PAID" },
  ] });
  const metrics = await attentionMetrics(db, w.id, 30);
  assert.equal(metrics.counts.total, 2);
  assert.equal(metrics.counts.linked, 2);
  assert.equal(metrics.opportunities.reduce((sum, row) => sum + row.count, 0), 1);
  assert.equal(metrics.sales.length, 2);
  assert.equal(metrics.sales.find(row => row.currency === "PEN")?.amount, "150.25");
  assert.equal(metrics.sales.find(row => row.currency === "USD")?.count, 1);
  const emptyMetrics = await attentionMetrics(db, other.id, 30);
  assert.equal(emptyMetrics.counts.total, 0);
  assert.equal(emptyMetrics.sales.length, 0);
  const outcome = { kind: "outcome" as const, opportunityId: opportunity.id, expectedStatus: "OPEN", status: "WON", reason: "Customer accepted the proposal", operationKey: randomUUID() };
  const salesBeforeOutcome = await db.sale.count();
  await assert.rejects(mutateCustomerChat(db, actor, visitorId, outcome), ChatOperationError);
  await assert.rejects(mutateCustomerChat(db, commercial, visitorId, { ...outcome, reason: "" }), ChatOperationError);
  await Promise.all([mutateCustomerChat(db, commercial, visitorId, outcome), mutateCustomerChat(db, commercial, visitorId, outcome)]);
  assert.equal((await db.opportunity.findUniqueOrThrow({ where: { id: opportunity.id } })).status, "WON");
  assert.equal(await db.activityLog.count({ where: { opportunityId: opportunity.id, title: "Venta declarada por el equipo" } }), 1);
  assert.equal(await db.sale.count(), salesBeforeOutcome);
  await assert.rejects(mutateCustomerChat(db, commercial, visitorId, { ...outcome, status: "LOST" }), ChatOperationError);
  await assert.rejects(mutateCustomerChat(db, commercial, chat.id, { ...outcome, status: "LOST", operationKey: randomUUID() }), ChatOperationError);
  const config = defaultAttentionConfig("Synthetic company");
  config.domains = ["company.example"];
  config.installation = { position: "left", label: "Consultar disponibilidad", pages: ["/servicios"] };
  const legacyConfig: Partial<typeof config> = { ...config }; delete legacyConfig.installation;
  assert.equal(attentionConfigSchema.parse(legacyConfig).installation.position, "right");
  for (const invalid of ["//evil.example", "/foo?token=secret", "/foo#fragment", "https://evil.example"]) {
    assert.equal(attentionConfigSchema.safeParse({ ...config, installation: { ...config.installation, pages: [invalid] } }).success, false);
  }

  await assert.rejects(saveAttentionSettings(db, w.id, a.id, 0, "draft", config));
  await db.terraqoWorkspaceMember.create({ data: { workspaceId: w.id, userId: a.id, role: "OWNER" } });
  await db.terraqoWorkspace.update({ where: { id: w.id }, data: { settings: { unrelatedSetting: "preserve" } } });
  const saved = await saveAttentionSettings(db, w.id, a.id, 0, "draft", config);
  assert.equal(saved.published, null);
  await assert.rejects(saveAttentionSettings(db, w.id, a.id, 0, "publish"));
  const published = await saveAttentionSettings(db, w.id, a.id, saved.revision, "publish");
  assert.equal(published.published?.displayName, "Synthetic company");
  const changed = await saveAttentionSettings(db, w.id, a.id, published.revision, "draft", { ...config, greeting: "A different welcome message" });
  const next = await saveAttentionSettings(db, w.id, a.id, changed.revision, "publish");
  const rollback = await saveAttentionSettings(db, w.id, a.id, next.revision, "rollback");
  assert.equal(rollback.published?.greeting, config.greeting);
  assert.equal((await db.terraqoWorkspace.findUniqueOrThrow({ where: { id: w.id } })).settings && JSON.stringify((await db.terraqoWorkspace.findUniqueOrThrow({ where: { id: w.id } })).settings).includes("preserve"), true);
  assert.equal(attentionAvailability(config, new Date("2026-11-04T14:00:00Z")), true);
  assert.equal(attentionAvailability(config, new Date("2026-11-08T14:00:00Z")), false);
  assert.equal(attentionAccentText("#ffffff"), "#000000");
  assert.equal(attentionAccentText("#000000"), "#ffffff");
  let answerCalls = 0;
  const botInput = { question: "First question", operationKey: randomUUID() };
  const answer = async () => { answerCalls++; return { answer: "A useful answer", source: "fixture", confidence: 1, shouldEscalate: false }; };
  const replies = await Promise.all([postCustomerBot(db, w.id, botInput, true, answer), postCustomerBot(db, w.id, botInput, true, answer)]);
  assert.equal(replies[0].conversationId, replies[1].conversationId);
  assert.equal(answerCalls, 1);
  const botId = replies[0].conversationId;
  await assert.rejects(postCustomerBot(db, other.id, { ...botInput, conversationId: botId }, true, answer), PublicChatError);
  const handoff = { conversationId: botId, question: "Talk to advisor", operationKey: randomUUID() };
  const escalate = async () => ({ answer: "Our team will continue", source: "human-handoff", confidence: 1, shouldEscalate: true });
  const handoffs = await Promise.all([postCustomerBot(db, w.id, handoff, true, escalate), postCustomerBot(db, w.id, handoff, true, escalate)]);
  assert.equal(handoffs[0].escalatedChatId, handoffs[1].escalatedChatId);
  assert.ok(handoffs[0].escalatedChatId?.startsWith("visitor2_"));
  assert.equal(await db.chatMessage.count({ where: { conversationId: handoffs[0].escalatedChatId! } }), 4);
  assert.equal(await db.notification.count({ where: { href: `/admin/chat?conversation=${handoffs[0].escalatedChatId}` } }), 1);
  await assert.rejects(postCustomerBot(db, w.id, { ...handoff, question: "Different", operationKey: randomUUID() }, true, escalate), PublicChatError);
  const testSecret = "synthetic-secret-never-used-outside-tests";
  const token = issueCustomerChatAccess(w.id, visitorId, Date.now(), testSecret);
  assert.equal(verifyCustomerChatAccess(token, w.id, visitorId, Date.now(), testSecret), true);
  assert.equal(verifyCustomerChatAccess(token, other.id, visitorId, Date.now(), testSecret), false);
  assert.equal(verifyCustomerChatAccess(token, w.id, "other", Date.now(), testSecret), false);
  assert.equal(verifyCustomerChatAccess(token + "tampered", w.id, visitorId, Date.now(), testSecret), false);
  assert.equal(verifyCustomerChatAccess(token, w.id, visitorId, Date.now() + 91*86400000, testSecret), false);
  const historical = await db.chatConversation.create({ data: { terraqoWorkspaceId: w.id, customerName: "History fixture", messages: { create: Array.from({ length: 205 }, (_, index) => ({ id: `history-${String(index).padStart(3, "0")}`, sender: "customer", body: `Message ${index}`, createdAt: new Date("2026-11-01T12:00:00Z") })) } } });
  const latest = await customerChatHistory(db, w.id, historical.id);
  assert.equal(latest.messages.length, 100); assert.equal(latest.hasEarlier, true);
  const older = await customerChatHistory(db, w.id, historical.id, latest.messages[0].id);
  const oldest = await customerChatHistory(db, w.id, historical.id, older.messages[0].id);
  assert.equal(oldest.messages.length, 5); assert.equal(oldest.hasEarlier, false);
  assert.equal(new Set([...oldest.messages, ...older.messages, ...latest.messages].map(m => m.id)).size, 205);
  await assert.rejects(customerChatHistory(db, other.id, historical.id), PublicChatError);
  await assert.rejects(customerChatHistory(db, w.id, visitorId, latest.messages[0].id), PublicChatError);
  const context = await loadPublicAttentionContext(db, w.slug);
  const visible = publicAttentionPresentation(context)!;
  assert.equal(visible.displayName, config.displayName);
  assert.equal("domains" in visible, false);
  assert.equal("draft" in visible, false);
  assert.equal("settings" in visible, false);
  await assert.rejects(loadPublicAttentionContext(db, other.slug), PublicChatError);
  await assert.rejects(loadPublicAttentionContext(db, "nonexistent-workspace"), PublicChatError);
  assert.equal(publicAttentionPresentation(await loadPublicAttentionContext(db, null, other.id)), null);
  assert.equal(attentionOriginAllowed("https://company.example", "https://api.example", ["company.example"]), true);
  assert.equal(attentionOriginAllowed("https://evil-company.example", "https://api.example", ["company.example"]), false);
  assert.equal(attentionOriginAllowed("http://company.example", "https://api.example", ["company.example"]), false);
  assert.equal(attentionOriginAllowed("null", "https://api.example", ["company.example"]), false);
  await verifyAttentionRouting(db);
  await verifyChatHttp(db, w, other);
  await db.terraqoWorkspace.update({ where: { id: w.id }, data: { active: false } });
  await assert.rejects(loadPublicAttentionContext(db, w.slug), PublicChatError);
  console.log("PASS attention: tenant isolation, concurrent claim, assignment authorization, idempotent reply, payload conflict, owner preservation, cross-tenant transfer rejection, resolved state and transactional audit; public DTO excludes private user fields.");
 } finally { await db.$disconnect(); }
}
main().catch(e => { console.error(e.stack || e.message); process.exitCode = 1; });
